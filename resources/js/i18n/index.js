const initial = (() => {
    if (typeof window === 'undefined') return 'ar';
    const stored = window.localStorage.getItem('locale');
    return stored === 'en' ? 'en' : 'ar';
})();

export const locale = ref(initial);

export function translate(key, lang = locale.value, params = {}) {
    const table = translations[lang] ?? translations.ar;
    let value = table[key] ?? translations.ar[key] ?? key;

    Object.entries(params).forEach(([name, replacement]) => {
        value = value.replaceAll(`:${name}`, String(replacement));
    });

    return value;
}

export function setLocale(next) {
    locale.value = next === 'en' ? 'en' : 'ar';

    if (typeof window !== 'undefined') {
        window.localStorage.setItem('locale', locale.value);
        document.cookie = `locale=${locale.value};path=/;max-age=31536000;samesite=lax`;
        document.documentElement.lang = locale.value;
        document.documentElement.dir = locale.value === 'ar' ? 'rtl' : 'ltr';
    }
}

export function useI18n() {
    const dir = computed(() => (locale.value === 'ar' ? 'rtl' : 'ltr'));
    const isRtl = computed(() => locale.value === 'ar');

    const t = (key, params = {}) => translate(key, locale.value, params);

    const toggle = () => setLocale(locale.value === 'ar' ? 'en' : 'ar');

    return { locale, dir, isRtl, t, toggle, setLocale };
}

if (typeof window !== 'undefined') {
    setLocale(initial);
}
